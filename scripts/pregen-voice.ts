// Pre-generates the demo voice clips with ElevenLabs.
//
//   pnpm voice:pregen                 # all clips, `spoken` text
//   pnpm voice:pregen --tagged        # send `tagged` text (Eleven v3 audio tags)
//   pnpm voice:pregen --only=crypto-th,stay-th-counter --force
//   pnpm voice:pregen --dry-run       # list what would be generated, no key needed
//
// Reads demo/voice/voice-lines.json and writes apps/web/public/audio/<clip>.mp3 plus
// manifest.json. Each clip's manifest `text` is the engine voiceText for its scene and
// language (the `pause.manifestText` line); the web app only plays a clip while the engine
// still produces exactly that text, so stale numbers are never spoken.
//
// Env (or workers/api/.dev.vars): ELEVENLABS_API_KEY, ELEVENLABS_VOICE_ID
// (ELEVENLABS_VOICE_ID_TH / _EN override per language), ELEVENLABS_MODEL_ID (default eleven_v3).
// Without a key it prints what's missing and exits 0.

import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

type Lang = 'th' | 'en';
interface Line {
  manifestText?: string;
  display: string;
  spoken: string;
  tagged: string;
  clip_key: string;
  file: string;
}
interface VoiceLines {
  scenes: Record<string, Record<string, Partial<Record<Lang, Line>>>>;
}
interface ClipEntry {
  file: string;
  text: string;
  display: string;
  line: string;
  source: 'spoken' | 'tagged';
  model: string;
  voiceId: string;
}
interface Manifest {
  $comment: string;
  clips: Record<string, ClipEntry>;
}

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const LINES = join(ROOT, 'demo/voice/voice-lines.json');
const OUT = join(ROOT, 'apps/web/public/audio');
const MANIFEST = join(OUT, 'manifest.json');
const DEV_VARS = join(ROOT, 'workers/api/.dev.vars');
const OUTPUT_FORMAT = 'mp3_44100_128';
const LANGS: Lang[] = ['th', 'en'];

const args = process.argv.slice(2);
const flag = (name: string) => args.includes(`--${name}`);
const option = (name: string) => args.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3);
const field: 'spoken' | 'tagged' = flag('tagged') ? 'tagged' : 'spoken';
const only = option('only')?.split(',').map((s) => s.trim()).filter(Boolean);
const force = flag('force');
const dryRun = flag('dry-run');

if (flag('help')) {
  console.log('Usage: pnpm voice:pregen [--tagged] [--only=<key-prefix,...>] [--force] [--dry-run]');
  process.exit(0);
}

if (existsSync(DEV_VARS)) {
  try {
    process.loadEnvFile(DEV_VARS);
  } catch {
    // malformed .dev.vars: rely on the shell env
  }
}
const env = (name: string) => process.env[name]?.trim() || undefined;
const apiKey = env('ELEVENLABS_API_KEY');
const model = env('ELEVENLABS_MODEL_ID') ?? 'eleven_v3';
const voiceFor = (lang: Lang) => env(`ELEVENLABS_VOICE_ID_${lang.toUpperCase()}`) ?? env('ELEVENLABS_VOICE_ID');

interface Job {
  key: string;
  line: string;
  lang: Lang;
  entry: Line;
  match: string;
}

function jobs(data: VoiceLines): Job[] {
  const out: Job[] = [];
  for (const [scene, byLine] of Object.entries(data.scenes)) {
    for (const lang of LANGS) {
      const match = byLine.pause?.[lang]?.manifestText;
      if (!match) {
        console.warn(`skip ${scene}/${lang}: no pause.manifestText to key the clips on`);
        continue;
      }
      for (const [line, byLang] of Object.entries(byLine)) {
        const entry = byLang[lang];
        if (!entry) continue;
        const key = entry.clip_key;
        if (only && !only.some((p) => key.startsWith(p))) continue;
        out.push({ key, line, lang, entry, match });
      }
    }
  }
  return out;
}

function loadManifest(): Manifest {
  const fresh: Manifest = {
    $comment:
      'Generated by scripts/pregen-voice.ts from demo/voice/voice-lines.json. `text` is the engine voiceText for the scene and language; the web app plays a clip only while it matches.',
    clips: {},
  };
  if (!existsSync(MANIFEST)) return fresh;
  try {
    const m = JSON.parse(readFileSync(MANIFEST, 'utf8')) as Partial<Manifest>;
    return { ...fresh, clips: m.clips ?? {} };
  } catch {
    return fresh;
  }
}

async function synthesize(text: string, voiceId: string): Promise<Uint8Array> {
  const base = env('ELEVENLABS_API_BASE') ?? 'https://api.elevenlabs.io';
  const url = `${base}/v1/text-to-speech/${encodeURIComponent(voiceId)}?output_format=${OUTPUT_FORMAT}`;
  for (let attempt = 0; ; attempt++) {
    const res = await fetch(url, {
      method: 'POST',
      headers: { 'xi-api-key': apiKey!, 'Content-Type': 'application/json', Accept: 'audio/mpeg' },
      body: JSON.stringify({ text, model_id: model }),
      signal: AbortSignal.timeout(60_000),
    });
    if (res.ok) return new Uint8Array(await res.arrayBuffer());
    const retryable = res.status === 429 || res.status >= 500;
    const detail = (await res.text().catch(() => '')).slice(0, 300);
    if (!retryable || attempt >= 2) throw new Error(`ElevenLabs ${res.status}: ${detail}`);
    await new Promise((r) => setTimeout(r, 2000 * 2 ** attempt));
  }
}

async function main(): Promise<number> {
  const todo = jobs(JSON.parse(readFileSync(LINES, 'utf8')) as VoiceLines);
  if (todo.length === 0) {
    console.log('Nothing to generate (check --only).');
    return 0;
  }

  if (dryRun) {
    const chars = todo.reduce((n, j) => n + j.entry[field].length, 0);
    for (const j of todo) console.log(`${j.key.padEnd(26)} ${String(j.entry[field].length).padStart(4)} chars  ${j.entry[field]}`);
    console.log(`\n${todo.length} clips, ${chars} characters of \`${field}\` text, model ${model}. Dry run: nothing written.`);
    return 0;
  }

  if (!apiKey) {
    console.log('ELEVENLABS_API_KEY is not set (env or workers/api/.dev.vars). Skipping voice pre-generation; the app uses live TTS or browser speech.');
    return 0;
  }
  const missingVoice = LANGS.filter((l) => todo.some((j) => j.lang === l) && !voiceFor(l));
  if (missingVoice.length) {
    console.error(`Set ELEVENLABS_VOICE_ID (or ELEVENLABS_VOICE_ID_${missingVoice[0]!.toUpperCase()}) to choose the voice.`);
    return 1;
  }

  mkdirSync(OUT, { recursive: true });
  const manifest = loadManifest();
  let made = 0;
  let failed = 0;
  for (const j of todo) {
    const voiceId = voiceFor(j.lang)!;
    const file = join(OUT, j.entry.file);
    const text = j.entry[field];
    const prev = manifest.clips[j.key];
    const upToDate = existsSync(file) && statSync(file).size > 0 && prev?.voiceId === voiceId && prev.model === model && prev.source === field;
    if (!force && upToDate) {
      console.log(`= ${j.key} (exists; --force to regenerate)`);
    } else {
      try {
        const started = Date.now();
        const audio = await synthesize(text, voiceId);
        writeFileSync(file, audio);
        made++;
        console.log(`+ ${j.key}  ${(audio.byteLength / 1024).toFixed(0)} KB  ${Date.now() - started} ms`);
      } catch (e) {
        failed++;
        console.error(`! ${j.key}: ${e instanceof Error ? e.message : String(e)}`);
        continue;
      }
    }
    manifest.clips[j.key] = { file: j.entry.file, text: j.match, display: j.entry.display, line: j.line, source: field, model, voiceId };
  }

  manifest.clips = Object.fromEntries(Object.entries(manifest.clips).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`\n${made} generated, ${failed} failed, manifest: ${Object.keys(manifest.clips).length} clips → ${MANIFEST.slice(ROOT.length + 1)}`);
  return failed ? 1 : 0;
}

main().then(
  (code) => process.exit(code),
  (e: unknown) => {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  },
);
